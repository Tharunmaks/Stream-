#!/usr/bin/env python3
"""Write src/es_unicode.h: the general category of every code point, as ranges.

    python3 scripts/gen_unicode.py [UnicodeData.txt]

With a UnicodeData.txt from https://www.unicode.org/Public/UCD/latest/ucd/ the table follows that
Unicode version (the same source llama.cpp uses); without one it uses Python's unicodedata.
"""
import os
import sys
import unicodedata

FLAG = {'Cn': 1, 'Cc': 128, 'Cf': 128, 'Co': 128, 'Cs': 128,
        'Ll': 4, 'Lm': 4, 'Lo': 4, 'Lt': 4, 'Lu': 4,
        'Mc': 16, 'Me': 16, 'Mn': 16,
        'Nd': 2, 'Nl': 2, 'No': 2,
        'Pc': 32, 'Pd': 32, 'Pe': 32, 'Pf': 32, 'Pi': 32, 'Po': 32, 'Ps': 32,
        'Sc': 64, 'Sk': 64, 'Sm': 64, 'So': 64,
        'Zl': 8, 'Zp': 8, 'Zs': 8}
N = 0x110000


def from_ucd(path):
    flags = bytearray([1]) * N
    first = None
    for line in open(path, encoding='utf-8'):
        f = line.split(';')
        cp, name, cat = int(f[0], 16), f[1], f[2]
        if name.endswith(', First>'):
            first = cp
            continue
        if name.endswith(', Last>'):
            for c in range(first, cp + 1):
                flags[c] = FLAG[cat]
            continue
        flags[cp] = FLAG[cat]
    return flags, 'UnicodeData.txt ' + os.path.basename(os.path.dirname(os.path.abspath(path)))


def from_python():
    flags = bytearray(N)
    for c in range(N):
        flags[c] = FLAG[unicodedata.category(chr(c))]
    return flags, 'Python unicodedata ' + unicodedata.unidata_version


flags, src = from_ucd(sys.argv[1]) if len(sys.argv) > 1 else from_python()
ranges = [(0, flags[0])]
for c in range(1, N):
    if flags[c] != ranges[-1][1]:
        ranges.append((c, flags[c]))

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'es_unicode.h')
with open(out, 'w') as o:
    o.write('/* Generated by scripts/gen_unicode.py from %s. Do not edit.\n' % src)
    o.write(' * Each entry: (first code point << 8) | category flags; a range lasts until the next entry. */\n')
    o.write('#ifndef ES_UNICODE_H\n#define ES_UNICODE_H\n#include <stdint.h>\n')
    o.write('enum { ESU_UNDEF = 1, ESU_NUMBER = 2, ESU_LETTER = 4, ESU_SEPARATOR = 8, ESU_MARK = 16, '
            'ESU_PUNCT = 32, ESU_SYMBOL = 64, ESU_CONTROL = 128 };\n')
    o.write('static const uint32_t ES_UNI_RANGES[%d] = {\n' % len(ranges))
    for i in range(0, len(ranges), 8):
        o.write('    ' + ', '.join('0x%08x' % ((s << 8) | f) for s, f in ranges[i:i + 8]) + ',\n')
    o.write('};\n#endif\n')
print('wrote', out, len(ranges), 'ranges from', src)
