#!/usr/bin/env python3
"""Embed tools/es_graft_anchor.jsonl (general questions and text that a graft must leave alone) into tools/es_graft_anchor.h."""
import os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(root, 'tools', 'es_graft_anchor.jsonl'), 'rb').read()
out = ['/* generated by scripts/gen_anchor.py from tools/es_graft_anchor.jsonl: do not edit */', 'static const char ES_GRAFT_ANCHOR[] =']
for line in src.decode('utf-8').splitlines(True):
    out.append('    "' + line.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"')
out[-1] += ';'
open(os.path.join(root, 'tools', 'es_graft_anchor.h'), 'w').write('\n'.join(out) + '\n')
