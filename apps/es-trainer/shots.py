from playwright.sync_api import sync_playwright
U="http://127.0.0.1:8765/"; D="screenshots/"
with sync_playwright() as p:
    b=p.chromium.launch(); pg=b.new_page(viewport={"width":390,"height":844},device_scale_factor=2)
    pg.goto(U); pg.wait_for_timeout(1200)
    pg.click("[data-t=train]"); pg.wait_for_timeout(500); pg.screenshot(path=D+"0_train_empty.png")
    pg.click("[data-t=setup]")
    pg.select_option("#data",label="qa_sample.jsonl"); pg.fill("#run","ui_demo"); pg.fill("#steps","15"); pg.fill("#lr","1e-3")
    pg.evaluate("scrollTo(0,0)"); pg.wait_for_timeout(600); pg.screenshot(path=D+"1_setup.png"); pg.evaluate("scrollTo(0,9999)"); pg.wait_for_timeout(300); pg.screenshot(path=D+"1b_setup_options.png")
    pg.click("#go"); pg.wait_for_timeout(22000)
    pg.screenshot(path=D+"2_training.png")
    pg.click("#stop"); pg.wait_for_function("document.getElementById('pilltxt').textContent=='Stopped'",timeout=60000)
    pg.wait_for_timeout(800); pg.screenshot(path=D+"2b_stopped.png")
    pg.click("#resume"); pg.wait_for_function("document.getElementById('pilltxt').textContent=='Done'",timeout=180000)
    pg.wait_for_timeout(1500); pg.screenshot(path=D+"2c_done.png")
    pg.click("[data-t=chat]"); pg.wait_for_timeout(800); pg.select_option("#crun","ui_demo")
    pg.fill("#cin","What does LoRA train?"); pg.click("#send")
    pg.wait_for_selector(".b.bot small",timeout=180000); pg.screenshot(path=D+"3_chat.png")
    pg.click("[data-t=files]"); pg.wait_for_timeout(800)
    pg.click("[data-exp=ui_demo]"); pg.wait_for_selector("a[href='/dl/ui_demo.gguf']",timeout=60000)
    pg.wait_for_timeout(500); pg.screenshot(path=D+"4_downloads.png")
    d=b.new_page(viewport={"width":1366,"height":900}); d.goto(U); d.wait_for_timeout(800); d.click("[data-t=train]"); d.wait_for_timeout(1500)
    d.screenshot(path=D+"5_desktop_train.png")
    print(pg.inner_text("#msgs")); b.close()
